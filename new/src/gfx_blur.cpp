bool Blur::CreateDeviceObjects(IDXGISwapChain* swap_chain) {
    if (!swap_chain || !device_) {
        nl::Log("Blur::CreateDeviceObjects: missing device/swap");
        return false;
    }

    DestroyDeviceObjects();
    swap_chain_ = swap_chain;

    Microsoft::WRL::ComPtr<ID3D11Texture2D> back_buffer;
    HRESULT hr = swap_chain->GetBuffer(0, IID_PPV_ARGS(back_buffer.GetAddressOf()));
    if (FAILED(hr) || !back_buffer) {
        LogBlurHr("Blur GetBuffer", hr);
        return false;
    }

    D3D11_TEXTURE2D_DESC texture_desc = {};
    back_buffer->GetDesc(&texture_desc);
    width_ = texture_desc.Width;
    height_ = texture_desc.Height;
    half_width_ = width_ >> 1;
    if (half_width_ < 1) half_width_ = 1;
    half_height_ = height_ >> 1;
    if (half_height_ < 1) half_height_ = 1;

    if (!vs_) {
        hr = device_->CreateVertexShader(shaders::kVsBytecode,
                                         sizeof(shaders::kVsBytecode) - 1,
                                         nullptr, vs_.GetAddressOf());
        if (FAILED(hr)) {
            LogBlurHr("Blur CreateVertexShader", hr);
            return false;
        }
    }

    if (!downsample_ps_) {
        hr = device_->CreatePixelShader(shaders::kDownsampleBytecode,
                                        sizeof(shaders::kDownsampleBytecode) - 1,
                                        nullptr, downsample_ps_.GetAddressOf());
        if (FAILED(hr)) {
            LogBlurHr("Blur CreatePixelShader(downsample)", hr);
            return false;
        }
    }

    if (!blur_ps_) {
        hr = device_->CreatePixelShader(shaders::kBlurBytecode,
                                        sizeof(shaders::kBlurBytecode) - 1,
                                        nullptr, blur_ps_.GetAddressOf());
        if (FAILED(hr)) {
            LogBlurHr("Blur CreatePixelShader(blur)", hr);
            return false;
        }
    }

    if (!input_buffer_) {
        D3D11_BUFFER_DESC desc = {};
        desc.ByteWidth = sizeof(BlurInputBuffer);
        desc.Usage = D3D11_USAGE_DYNAMIC;
        desc.BindFlags = D3D11_BIND_CONSTANT_BUFFER;
        desc.CPUAccessFlags = D3D11_CPU_ACCESS_WRITE;
        hr = device_->CreateBuffer(&desc, nullptr, input_buffer_.GetAddressOf());
        if (FAILED(hr)) return false;
    }

    if (!sampler_) {
        D3D11_SAMPLER_DESC desc = {};
        desc.Filter = D3D11_FILTER_MIN_MAG_MIP_LINEAR;
        desc.AddressU = D3D11_TEXTURE_ADDRESS_CLAMP;
        desc.AddressV = D3D11_TEXTURE_ADDRESS_CLAMP;
        desc.AddressW = D3D11_TEXTURE_ADDRESS_CLAMP;
        desc.MaxLOD = FLT_MAX;
        hr = device_->CreateSamplerState(&desc, sampler_.GetAddressOf());
        if (FAILED(hr)) return false;
    }

    if (!rasterizer_) {
        D3D11_RASTERIZER_DESC desc = {};
        desc.FillMode = D3D11_FILL_SOLID;
        desc.CullMode = D3D11_CULL_NONE;
        hr = device_->CreateRasterizerState(&desc, rasterizer_.GetAddressOf());
        if (FAILED(hr)) return false;
    }

    if (!depth_stencil_) {
        D3D11_DEPTH_STENCIL_DESC desc = {};
        hr = device_->CreateDepthStencilState(&desc, depth_stencil_.GetAddressOf());
        if (FAILED(hr)) return false;
    }

    if (!blend_) {
        D3D11_BLEND_DESC desc = {};
        desc.RenderTarget[0].RenderTargetWriteMask = D3D11_COLOR_WRITE_ENABLE_ALL;
        hr = device_->CreateBlendState(&desc, blend_.GetAddressOf());
        if (FAILED(hr)) return false;
    }

    D3D11_TEXTURE2D_DESC capture_desc = {};
    capture_desc.Width = width_;
    capture_desc.Height = height_;
    capture_desc.MipLevels = 1;
    capture_desc.ArraySize = 1;
    capture_desc.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
    capture_desc.SampleDesc.Count = 1;
    capture_desc.BindFlags = D3D11_BIND_SHADER_RESOURCE;

    hr = device_->CreateTexture2D(&capture_desc, nullptr,
                                  capture_texture_.ReleaseAndGetAddressOf());
    if (FAILED(hr)) {
        DestroyDeviceObjects();
        return false;
    }
    hr = device_->CreateShaderResourceView(capture_texture_.Get(), nullptr,
                                           capture_srv_.ReleaseAndGetAddressOf());
    if (FAILED(hr)) {
        DestroyDeviceObjects();
        return false;
    }

    auto create_target = [&](const D3D11_TEXTURE2D_DESC& source_desc,
                             Microsoft::WRL::ComPtr<ID3D11Texture2D>& texture,
                             Microsoft::WRL::ComPtr<ID3D11ShaderResourceView>& srv,
                             Microsoft::WRL::ComPtr<ID3D11RenderTargetView>& rtv) {
        D3D11_TEXTURE2D_DESC desc = source_desc;
        desc.Width = half_width_;
        desc.Height = half_height_;
        desc.BindFlags = D3D11_BIND_SHADER_RESOURCE | D3D11_BIND_RENDER_TARGET;

        if (FAILED(device_->CreateTexture2D(&desc, nullptr,
                                            texture.ReleaseAndGetAddressOf())))
            return false;
        if (FAILED(device_->CreateShaderResourceView(texture.Get(), nullptr,
                                                     srv.ReleaseAndGetAddressOf())))
            return false;
        return SUCCEEDED(device_->CreateRenderTargetView(texture.Get(), nullptr,
                                                         rtv.ReleaseAndGetAddressOf()));
    };

    if (!create_target(capture_desc, downsample_texture_, downsample_srv_, downsample_rtv_) ||
        !create_target(capture_desc, blur_texture_, blur_srv_, blur_rtv_)) {
        DestroyDeviceObjects();
        return false;
    }

    if (context_ && blur_rtv_) {
        const float clear[4] = {0.0f, 0.01f, 0.01f, 1.0f};
        context_->ClearRenderTargetView(blur_rtv_.Get(), clear);
    }
    ready_ = true;
    return true;
}

void Blur::DestroyDeviceObjects() {
    blur_rtv_.Reset();
    blur_srv_.Reset();
    blur_texture_.Reset();
    downsample_rtv_.Reset();
    downsample_srv_.Reset();
    downsample_texture_.Reset();
    capture_srv_.Reset();
    capture_texture_.Reset();
    width_ = 0;
    height_ = 0;
    half_width_ = 0;
    half_height_ = 0;
    ready_ = false;
    capture_pending_ = false;
}

bool Blur::Init(ID3D11Device* device, ID3D11DeviceContext* context,
                IDXGISwapChain* swap_chain) {
    device_ = device;
    context_ = context;
    return CreateDeviceObjects(swap_chain);
}

void Blur::OnResize(IDXGISwapChain* swap_chain) {
    if (!CreateDeviceObjects(swap_chain)) {
        width_ = 0;
        height_ = 0;
        half_width_ = 0;
        half_height_ = 0;
        ready_ = false;
        capture_pending_ = false;
    }
    has_result_ = false;
}

void Blur::Shutdown() {
    DestroyDeviceObjects();
    blend_.Reset();
    depth_stencil_.Reset();
    rasterizer_.Reset();
    sampler_.Reset();
    input_buffer_.Reset();
    blur_ps_.Reset();
    downsample_ps_.Reset();
    vs_.Reset();
    has_result_ = false;
    ready_ = false;
    capture_pending_ = false;
    device_ = nullptr;
    context_ = nullptr;
    swap_chain_ = nullptr;
}

bool Blur::RunBlur() {
    if (!context_ || !swap_chain_ || !capture_texture_ || !blur_rtv_ || !downsample_rtv_)
        return false;

    Microsoft::WRL::ComPtr<ID3D11RenderTargetView> old_rtv;
    Microsoft::WRL::ComPtr<ID3D11DepthStencilView> old_dsv;
    context_->OMGetRenderTargets(1, old_rtv.GetAddressOf(), old_dsv.GetAddressOf());
    if (!old_rtv) return false;

    PixelBindings pixel_bindings(context_);
    ID3D11ShaderResourceView* null_srvs[4] = {};
    context_->PSSetShaderResources(0, 4, null_srvs);

    Microsoft::WRL::ComPtr<ID3D11Resource> old_resource;
    old_rtv->GetResource(old_resource.GetAddressOf());
    if (!old_resource) return false;

    UINT viewport_count = 1;
    D3D11_VIEWPORT old_viewport = {};
    context_->RSGetViewports(&viewport_count, &old_viewport);

    bool restore_frame_state = true;
    bool clear_ps0 = false;
    bool result = false;

    do {
        Microsoft::WRL::ComPtr<ID3D11Texture2D> source_texture;
        if (SUCCEEDED(old_resource.As(&source_texture)) && source_texture) {
            D3D11_TEXTURE2D_DESC source_desc = {};
            source_texture->GetDesc(&source_desc);
            if (source_desc.Width != width_ || source_desc.Height != height_ ||
                source_desc.Format != DXGI_FORMAT_R8G8B8A8_UNORM)
                break;
        }

        clear_ps0 = true;
        context_->OMSetRenderTargets(0, nullptr, nullptr);
        context_->CopyResource(capture_texture_.Get(), old_resource.Get());

        const float clear[4] = {0.0f, 0.01f, 0.01f, 1.0f};
        context_->ClearRenderTargetView(downsample_rtv_.Get(), clear);
        context_->ClearRenderTargetView(blur_rtv_.Get(), clear);

        ID3D11SamplerState* sampler = sampler_.Get();
        ID3D11Buffer* input_buffer = input_buffer_.Get();
        context_->VSSetShader(vs_.Get(), nullptr, 0);
        context_->PSSetSamplers(0, 1, &sampler);
        context_->PSSetConstantBuffers(0, 1, &input_buffer);
        context_->IASetInputLayout(nullptr);
        context_->IASetPrimitiveTopology(D3D11_PRIMITIVE_TOPOLOGY_TRIANGLESTRIP);
        context_->RSSetState(rasterizer_.Get());
        context_->OMSetBlendState(blend_.Get(), nullptr, 0xFFFFFFFF);
        context_->OMSetDepthStencilState(depth_stencil_.Get(), 0);

        auto upload_constants = [&](float texture_width, float texture_height,
                                    float directions, float quality, float radius) {
            D3D11_MAPPED_SUBRESOURCE mapped = {};
            if (FAILED(context_->Map(input_buffer_.Get(), 0, D3D11_MAP_WRITE_DISCARD,
                                     0, &mapped)))
                return false;
            auto* constants = static_cast<BlurInputBuffer*>(mapped.pData);
            constants->texture_size[0] = texture_width;
            constants->texture_size[1] = texture_height;
            constants->blur_directions = directions;
            constants->blur_quality = quality;
            constants->blur_radius = radius;
            constants->padding[0] = 0.0f;
            constants->padding[1] = 0.0f;
            constants->padding[2] = 0.0f;
            context_->Unmap(input_buffer_.Get(), 0);
            return true;
        };

        if (!upload_constants(static_cast<float>(width_), static_cast<float>(height_),
                              1.0f, 1.0f, 0.0f))
            break;

        D3D11_VIEWPORT half_viewport = {};
        half_viewport.Width = static_cast<float>(half_width_);
        half_viewport.Height = static_cast<float>(half_height_);
        half_viewport.MaxDepth = 1.0f;

        ID3D11ShaderResourceView* null_srv = nullptr;
        ID3D11RenderTargetView* target = downsample_rtv_.Get();
        ID3D11ShaderResourceView* source = capture_srv_.Get();
        context_->PSSetShaderResources(0, 1, &null_srv);
        context_->OMSetRenderTargets(1, &target, nullptr);
        context_->RSSetViewports(1, &half_viewport);
        context_->PSSetShader(downsample_ps_.Get(), nullptr, 0);
        context_->PSSetShaderResources(0, 1, &source);
        context_->Draw(3, 0);
        context_->PSSetShaderResources(0, 1, &null_srv);

        if (!upload_constants(static_cast<float>(half_width_),
                              static_cast<float>(half_height_), 16.0f, 4.0f, 12.0f))
            break;

        target = blur_rtv_.Get();
        source = downsample_srv_.Get();
        context_->PSSetShaderResources(0, 1, &null_srv);
        context_->OMSetRenderTargets(1, &target, nullptr);
        context_->RSSetViewports(1, &half_viewport);
        context_->PSSetShader(blur_ps_.Get(), nullptr, 0);
        context_->PSSetShaderResources(0, 1, &source);
        context_->Draw(3, 0);
        context_->PSSetShaderResources(0, 1, &null_srv);
        result = true;
    } while (false);

    if (clear_ps0) {
        ID3D11ShaderResourceView* null_srv = nullptr;
        context_->PSSetShaderResources(0, 1, &null_srv);
    }
    if (restore_frame_state) {
        ID3D11RenderTargetView* target = old_rtv.Get();
        context_->OMSetRenderTargets(1, &target, old_dsv.Get());
        if (viewport_count != 0)
            context_->RSSetViewports(viewport_count, &old_viewport);
    }
    return result;
}

bool Blur::EnsureSize() {
    if (!swap_chain_) return blur_srv_.Get() != nullptr;

    Microsoft::WRL::ComPtr<ID3D11Texture2D> back_buffer;
    HRESULT hr = swap_chain_->GetBuffer(0, IID_PPV_ARGS(back_buffer.GetAddressOf()));
    if (SUCCEEDED(hr) && back_buffer) {
        D3D11_TEXTURE2D_DESC desc = {};
        back_buffer->GetDesc(&desc);
        if (desc.Width != width_ || desc.Height != height_)
            return CreateDeviceObjects(swap_chain_);
    }
    return blur_srv_.Get() != nullptr;
}

bool Blur::QueueCapture(bool force) {
    if (!ready_ || !EnsureSize() || !blur_srv_) return false;
    if (force || !has_result_) capture_pending_ = true;
    return true;
}

void Blur::ExecutePending() {
    if (!ready_ || !capture_pending_) return;
    const bool succeeded = RunBlur();
    capture_pending_ = false;
    has_result_ = succeeded && blur_srv_.Get() != nullptr;
}

