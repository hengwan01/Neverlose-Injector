struct BlurInputBuffer {
    float texture_size[2];
    float blur_directions;
    float blur_quality;
    float blur_radius;
    float padding[3];
};
static_assert(sizeof(BlurInputBuffer) == 32);

struct PixelBindings {
    explicit PixelBindings(ID3D11DeviceContext* context) : context(context) {
        context->PSGetShaderResources(0, 4, srv);
        context->PSGetSamplers(0, 1, &sampler);
    }

    ~PixelBindings() {
        context->PSSetShaderResources(0, 4, srv);
        context->PSSetSamplers(0, 1, &sampler);
        for (auto*& view : srv) {
            if (view) view->Release();
        }
        if (sampler) sampler->Release();
    }

    PixelBindings(const PixelBindings&) = delete;
    PixelBindings& operator=(const PixelBindings&) = delete;

    ID3D11DeviceContext* context;
    ID3D11ShaderResourceView* srv[4] = {};
    ID3D11SamplerState* sampler = nullptr;
};

void LogBlurHr(const char* operation, HRESULT hr) {
    nl::Log("%s failed (hr=0x%08X)", operation, static_cast<unsigned int>(hr));
}

